/**
 * Campaign Repair — reattach keyword briefs after a schema rollback.
 * ==================================================================
 *
 * WHY THIS EXISTS
 *
 * On 2026-07-29 a concurrent session reverted prisma/schema.prisma (dropping
 * `ContentGap.brief`, `WritingJob.brief`, `GeneratedGuide.targetKeyword` /
 * `relatedKeywords`) and ran `prisma db push`, which syncs the database DOWN to
 * the schema — so Postgres dropped those columns and every stored brief with
 * them. The pipeline then froze outright: production's deployed Prisma client
 * still selected `brief`, so every `writingJob.findUnique` failed against a
 * column that no longer existed.
 *
 * Recovery is possible because the content plan is DERIVED, not authored: it is
 * rebuilt deterministically from lib/agents/topic-strategy.ts + the keyword
 * corpus, so the briefs can be regenerated byte-for-byte rather than restored
 * from a backup. That property is worth preserving — it is what turns a
 * destructive schema rollback into a five-minute repair.
 *
 * WHY NOT JUST RE-RUN THE SEEDER: seedKeywordCampaign() finds an existing gap by
 * reading `brief.id` off the row. After the rollback every `brief` is NULL, so
 * nothing matches and a re-seed would insert 69 DUPLICATE gaps instead of
 * updating the existing ones. This script matches on `query` instead — which
 * holds the brief's primaryKeyword verbatim (see campaignQueryFor) and survived
 * the rollback untouched.
 *
 * USAGE
 *   npx tsx scripts/seo/campaign-repair.ts --env=.env.production.local
 *   --dry   report what would change, write nothing
 */

import fs from 'fs';
import path from 'path';

const argv = process.argv.slice(2);
const flag = (n: string) => {
  const hit = argv.find((a) => a === `--${n}` || a.startsWith(`--${n}=`));
  return hit ? (hit.includes('=') ? hit.split('=').slice(1).join('=') : 'true') : undefined;
};
const DRY = Boolean(flag('dry'));

function loadEnvFile(file: string): void {
  if (!fs.existsSync(file)) return;
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    const m = line.match(/^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/);
    if (!m) continue;
    const value = m[2].trim().replace(/^["']|["']$/g, '');
    if (value && !process.env[m[1]]) process.env[m[1]] = value;
  }
}

async function main() {
  const extra = flag('env');
  if (extra) loadEnvFile(path.resolve(extra));
  loadEnvFile('.env.local');
  loadEnvFile('.env');

  if (!process.env.DATABASE_URL) {
    console.error('DATABASE_URL is not set.');
    process.exit(1);
  }

  const { buildContentPlan } = await import('@/lib/agents/topic-strategy');
  const { prisma } = await import('@/lib/db');

  const plan = buildContentPlan();
  const briefByKeyword = new Map(plan.map((b) => [b.primaryKeyword, b]));
  console.log(`plan rebuilt: ${plan.length} briefs\n`);

  // --- 1. Reattach briefs to the campaign's ContentGaps ---------------------
  const gaps: Array<{ id: string; query: string; brief: unknown; severity: number }> =
    await prisma.contentGap.findMany({
      where: { source: 'keyword-campaign' },
      select: { id: true, query: true, brief: true, severity: true },
    });

  let gapsFixed = 0;
  let gapsAlreadyOk = 0;
  let gapsUnmatched = 0;

  for (const gap of gaps) {
    if (gap.brief) { gapsAlreadyOk += 1; continue; }
    const brief = briefByKeyword.get(gap.query);
    if (!brief) { gapsUnmatched += 1; console.log(`  UNMATCHED gap: "${gap.query}"`); continue; }
    if (!DRY) {
      await prisma.contentGap.update({
        where: { id: gap.id },
        data: { brief: brief as unknown as object, severity: brief.priority },
      });
    }
    gapsFixed += 1;
  }

  console.log(`gaps: ${gapsFixed} reattached, ${gapsAlreadyOk} already had a brief, ${gapsUnmatched} unmatched (of ${gaps.length})`);

  // --- 2. Reattach briefs to in-flight WritingJobs --------------------------
  // Jobs are matched through their gap, not by query, so a job keeps the brief
  // of the gap it actually claimed.
  const gapBriefById = new Map<string, unknown>();
  for (const gap of await prisma.contentGap.findMany({
    where: { source: 'keyword-campaign' },
    select: { id: true, brief: true },
  })) {
    if (gap.brief) gapBriefById.set(gap.id, gap.brief);
  }

  const jobs: Array<{ id: string; gapId: string; query: string; brief: unknown; stage: string; titleHe: string | null }> =
    await prisma.writingJob.findMany({
      where: { stage: { notIn: ['done', 'failed'] } },
      select: { id: true, gapId: true, query: true, brief: true, stage: true, titleHe: true },
    });

  let jobsFixed = 0;
  let jobsSkipped = 0;
  // A job that already passed `plan` was planned while the brief was still
  // present, so its title and section blueprint are correctly targeted. It only
  // needs the brief back for the SECTION prompts, which are still ahead of it.
  let jobsPlannedWithBrief = 0;

  for (const job of jobs) {
    if (job.brief) { jobsSkipped += 1; continue; }
    const brief = gapBriefById.get(job.gapId);
    if (!brief) { jobsSkipped += 1; continue; }
    if (!DRY) {
      await prisma.writingJob.update({ where: { id: job.id }, data: { brief: brief as object } });
    }
    jobsFixed += 1;
    if (job.titleHe) jobsPlannedWithBrief += 1;
  }

  console.log(`jobs: ${jobsFixed} reattached, ${jobsSkipped} skipped (of ${jobs.length} active)`);
  console.log(`      ${jobsPlannedWithBrief} of those already had a targeted title/outline from before the rollback`);

  // --- 3. Flag anything planned WITHOUT a brief -----------------------------
  // A job that reached `plan` during the outage was planned blind. Its H1 and
  // outline target nothing, so it must be replanned rather than finished.
  const blind: Array<{ id: string; query: string; titleHe: string | null }> = [];
  for (const job of jobs) {
    if (!job.titleHe) continue;
    const brief = gapBriefById.get(job.gapId) as { primaryKeyword?: string } | undefined;
    if (brief?.primaryKeyword && !job.titleHe.includes(brief.primaryKeyword)) {
      blind.push({ id: job.id, query: job.query, titleHe: job.titleHe });
    }
  }

  if (blind.length > 0) {
    console.log(`\n${blind.length} job(s) have an H1 missing their exact keyword — planned during the outage:`);
    for (const b of blind) console.log(`  - "${b.query}" -> ${b.titleHe}`);
    if (!DRY) {
      // Send them back to `plan`. The research is still valid and expensive, so
      // we keep it; only the blind title/outline is discarded.
      await prisma.writingJob.updateMany({
        where: { id: { in: blind.map((b) => b.id) } },
        data: { stage: 'plan', titleHe: null, sectionPlan: undefined, sectionIndex: 0, sectionContents: [], attempts: 0 },
      });
      console.log(`  -> reset to stage 'plan' (research kept, blind outline discarded)`);
    }
  } else {
    console.log('\nno blind-planned jobs — every planned title contains its exact keyword.');
  }

  await prisma.$disconnect();
  console.log(DRY ? '\n(dry run — nothing written)' : '\nrepair complete.');
}

main().catch((e) => {
  console.error('\ncampaign-repair failed:', e);
  process.exit(1);
});
